# Run once after copying BZ Music to a new PC.
# - Writes local.properties with detected Android SDK
# - Prefers offline gradle-8.13-bin.zip when present
# - Optionally wires gradle-truststore.jks for SSL issues
# - Verifies release keystore files

param(
    [string]$SdkDir = "",
    [switch]$EnableTruststore,
    [switch]$ForceOnlineGradle
)

$ErrorActionPreference = "Stop"
$Root = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path
Set-Location $Root

function Find-AndroidSdk {
    param([string]$Hint)
    if ($Hint -and (Test-Path $Hint)) { return (Resolve-Path $Hint).Path }
    if ($env:ANDROID_HOME -and (Test-Path $env:ANDROID_HOME)) { return $env:ANDROID_HOME }
    if ($env:ANDROID_SDK_ROOT -and (Test-Path $env:ANDROID_SDK_ROOT)) { return $env:ANDROID_SDK_ROOT }
    $default = Join-Path $env:LOCALAPPDATA "Android\Sdk"
    if (Test-Path $default) { return $default }
    return $null
}

$sdk = Find-AndroidSdk -Hint $SdkDir
if (-not $sdk) {
    throw "Android SDK not found. Install Android Studio, or pass -SdkDir 'C:\path\to\Sdk'"
}

# local.properties (Gradle: escape : and \)
$sdkEscaped = $sdk.Replace('\', '\\').Replace(':', '\:')
@(
    "## Generated by scripts/setup-new-machine.ps1",
    "sdk.dir=$sdkEscaped"
) | Set-Content -Path (Join-Path $Root "local.properties") -Encoding ASCII
Write-Host "Wrote local.properties -> $sdk"

# Gradle wrapper: prefer local zip for offline portability
$wrapperProps = Join-Path $Root "gradle\wrapper\gradle-wrapper.properties"
$localZip = Join-Path $Root "gradle\wrapper\gradle-8.13-bin.zip"
$onlineUrl = "https\://services.gradle.org/distributions/gradle-8.13-bin.zip"
$lines = Get-Content $wrapperProps
if ((Test-Path $localZip) -and -not $ForceOnlineGradle) {
    $uriPath = ($localZip -replace '\\', '/')
    # file:///C:/path/to/zip
    $fileUrl = "file\:///" + ($uriPath -replace ':', '\:')
    $lines = $lines | ForEach-Object {
        if ($_ -match '^distributionUrl=') { "distributionUrl=$fileUrl" } else { $_ }
    }
    Write-Host "Gradle wrapper -> local zip: $localZip"
} else {
    $lines = $lines | ForEach-Object {
        if ($_ -match '^distributionUrl=') { "distributionUrl=$onlineUrl" } else { $_ }
    }
    Write-Host "Gradle wrapper -> online distribution"
}
# Ensure validate line was not corrupted by older setup runs
$lines = $lines | ForEach-Object {
    if ($_ -match '^validateDistributionUrl=' -or $_ -match '^validatedistributionUrl=') {
        "validateDistributionUrl=true"
    } else { $_ }
}
Set-Content -Path $wrapperProps -Value $lines -Encoding ASCII

# Optional SSL truststore (only if file exists and requested, or previous SSL issues)
$trust = Join-Path $Root "gradle-truststore.jks"
$gradleProps = Join-Path $Root "gradle.properties"
$baseProps = @"
org.gradle.jvmargs=-Xmx1536m -Dfile.encoding=UTF-8
org.gradle.parallel=true
android.useAndroidX=true
kotlin.code.style=official
android.nonTransitiveRClass=true
"@
if ((Test-Path $trust) -and $EnableTruststore) {
    $trustPath = ($trust -replace '\\', '/')
    $baseProps = @"
org.gradle.jvmargs=-Xmx1536m -Dfile.encoding=UTF-8 -Djavax.net.ssl.trustStore=$trustPath -Djavax.net.ssl.trustStorePassword=changeit
systemProp.javax.net.ssl.trustStore=$trustPath
systemProp.javax.net.ssl.trustStorePassword=changeit
org.gradle.parallel=true
android.useAndroidX=true
kotlin.code.style=official
android.nonTransitiveRClass=true
"@
    Write-Host "Enabled gradle-truststore.jks in gradle.properties"
} else {
    Write-Host "Truststore not injected (default). Re-run with -EnableTruststore if dependency downloads fail SSL."
}
Set-Content -Path $gradleProps -Value $baseProps.TrimEnd() -Encoding ASCII

# Verify signing materials
$jks = Join-Path $Root "muzika-release.jks"
$ksProps = Join-Path $Root "keystore.properties"
if (-not (Test-Path -LiteralPath $jks)) {
    Write-Warning "MISSING muzika-release.jks - cannot sign Play updates"
} else {
    Write-Host "Found muzika-release.jks ($((Get-Item -LiteralPath $jks).Length) bytes)"
}
if (-not (Test-Path -LiteralPath $ksProps)) {
    Write-Warning "MISSING keystore.properties - copy from backup or keystore.properties.example"
} else {
    Write-Host "Found keystore.properties"
}

Write-Host ""
Write-Host "Setup complete. Next:"
Write-Host "  .\gradlew.bat bundleRelease"
Write-Host "See PORTING.md for Play Console continuity."
